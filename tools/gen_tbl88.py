"""gen_tbl88.py - flattens the RTL8821C register tables of Linux rtw88 (rtw8821c_table.c) for the PCIe interface into
src/rtw88/r88_tbl.c of the RTL8821CE driver.

usage: python3 gen_tbl88.py <linux>/drivers/net/wireless/realtek/rtw88/rtw8821c_table.c src/rtw88/r88_tbl.c

The tables carry condition headers (rtw_parse_tbl_phy_cond, phy.c): a block applies when the board's RFE type
(eFuse 0xCA bits 4:0), package (eFuse 0xCA bit 5: 1, else 15), cut and interface match. The script evaluates them for
the PCIe interface and every RFE type / package, and writes one copy of each table per distinct result (for this
chip there are two: the default, and RFE 4 with package 1, which has its own AGC and RF-A tables). The driver picks
the copy with r88_tbl_variant() at run time. No cut-specific blocks exist for PCIe (the script checks). Only the RFE
types Linux supports are evaluated (0, 2, 4, 6: rtw8821c_rfe_defs); the driver uses variant 0 for any other.
"""
import re, sys

src = open(sys.argv[1], encoding='latin-1').read()
OUT = sys.argv[2]

def arr(name):
    m = re.search(r'static const u32 ' + name + r'\[\]\s*=\s*\{(.*?)\};', src, re.S)
    n = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]
    return list(zip(n[0::2], n[1::2]))

def cond(v):
    return dict(rfe=v & 0xff, intf=(v >> 8) & 0xf, pkg=(v >> 12) & 0xf, cut=(v >> 24) & 0xf,
                branch=(v >> 28) & 3, neg=(v >> 30) & 1, pos=(v >> 31) & 1)

def flat(t, rfe, pkg, cut=15, intf=1):                  # rtw_parse_tbl_phy_cond + check_positive
    out = []; m = True; sk = False; pc = None
    for a, d in t:
        c = cond(a)
        if c['pos']:
            if c['branch'] == 3: m, sk = True, False                  # ENDIF
            elif c['branch'] == 2: m = False if sk else True          # ELSE
            else: pc = c                                              # IF / ELIF
        elif c['neg']:
            if not sk:
                ok = not ((pc['cut'] and pc['cut'] != cut) or (pc['pkg'] and pc['pkg'] != pkg) or
                          (pc['intf'] and pc['intf'] != intf) or pc['rfe'] != rfe)
                m, sk = (True, True) if ok else (False, False)
            else:
                m = False
        elif m:
            out.append((a, d))
    return out

NAMES = ['mac', 'bb', 'agc', 'agc_btg_type2', 'rf_a']
tabs = {n: arr('rtw8821c_' + n) for n in NAMES}
combos = [(r, p) for r in (0, 2, 4, 6) for p in (15, 1)]   # the RFE types Linux supports (rtw8821c_rfe_defs)
variants = []                                            # distinct (tables) results
vmap = {}
for r, p in combos:
    res = tuple(tuple(flat(tabs[n], r, p)) for n in NAMES)
    if res not in variants:
        variants.append(res)
    vmap[(r, p)] = variants.index(res)
for cut in (0, 1, 2, 3):                                 # cut must not matter for PCIe
    for n in NAMES:
        assert flat(tabs[n], 0, 15, cut) == flat(tabs[n], 0, 15), (n, cut)
special = sorted(k for k, v in vmap.items() if v != 0)
print('variants', len(variants), 'non-default (rfe, pkg):', special)
for n in ('mac', 'bb'):
    assert all(v[NAMES.index(n)] == variants[0][NAMES.index(n)] for v in variants), n

def emit(f, cname, ctype, t, wide):
    f.write('const %s %s[%d] = {\n' % (ctype, cname, len(t)))
    for i, (a, v) in enumerate(t):
        f.write(('   {0x%X,0x%XUL},' if wide else '   {0x%X,0x%X},') % (a, v))
        if i % 4 == 3: f.write('\n')
    f.write('\n};\n')

with open(OUT, 'w', newline='\n') as f:
    f.write('/* SPDX-License-Identifier: GPL-2.0-only */\n/*\n')
    f.write(' * r88_tbl.c - RTL8821C MAC / baseband / AGC / RF-A initialisation tables, generated by tools/gen_tbl88.py from\n')
    f.write(' * Linux rtw88 rtw8821c_table.c (Copyright(c) 2018-2019 Realtek Corporation, GPL-2.0 OR BSD-3-Clause) for the PCIe\n')
    f.write(' * interface. Variant 1 = RFE type 4 with package 1 (eFuse 0xCA = 0x24), variant 0 = every other board.\n')
    f.write(' * Delay entries keep their codes (BB: 0xFE 50 ms, 0xFD 5 ms, 0xFC 1 ms, 0xFB 50 us, 0xFA 5 us, 0xF9 1 us;\n')
    f.write(' * RF: 0xFFE 50 ms, 0xFE 100 us), as rtw_phy_cfg_bb / rtw_phy_cfg_rf.\n */\n')
    f.write('#include "drv.h"\n#include "r88.h"\n\n')
    v0 = variants[0]
    emit(f, 'g88_mac_tbl', 'r88_mac_t', v0[0], False); f.write('const USHORT g88_mac_n = %d;\n\n' % len(v0[0]))
    emit(f, 'g88_bb_tbl', 'r88_bb_t', v0[1], True);  f.write('const USHORT g88_bb_n = %d;\n\n' % len(v0[1]))
    for vi, v in enumerate(variants):
        emit(f, 'g88_agc%d' % vi, 'r88_bb_t', v[2], True)
        emit(f, 'g88_agcbtg%d' % vi, 'r88_bb_t', v[3], True)
        emit(f, 'g88_rf%d' % vi, 'r88_rf_t', v[4], True)
    f.write('\nconst r88_tblset_t g88_tbls[%d] = {\n' % len(variants))
    for vi, v in enumerate(variants):
        f.write('   { g88_agc%d, %d, g88_agcbtg%d, %d, g88_rf%d, %d },\n' % (vi, len(v[2]), vi, len(v[3]), vi, len(v[4])))
    f.write('};\n\n')
    f.write('/* the table set for a board: RFE type (eFuse 0xCA bits 4:0), package (bit 5) */\n')
    f.write('USHORT r88_tbl_variant(UCHAR rfe, UCHAR pkg1)\n{\n')
    for (r, p) in special:
        f.write('   if (rfe == %d && %spkg1) return %d;\n' % (r, '' if p == 1 else '!', vmap[(r, p)]))
    f.write('   return 0;\n}\n')
print('written', OUT, 'sizes:', [len(x) for x in variants[0]], [len(x) for x in variants[-1]])
